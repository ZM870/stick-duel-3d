function createSkills({
  attackName,
  skill1Name,
  skill2Name,
  ultName,
  skill1Type = 'dash',
  skill2Style = 'orb',
  color,
  projectileColor,
  projectileTrail,
  ultColor,
  attackDamage = 50,
  skillDamage = 106,
  projectileDamage = 86,
  skill2Cost = 25,
  ultDamage = 292,
}) {
  const attack = {
    key: 'attack', name: attackName, short: '攻', type: 'melee',
    damage: attackDamage, range: 2.05, arc: 1.1,
    startup: 0.06, active: 0.09, recovery: 0.16,
    cooldown: 0.34, cost: 0,
    knockback: 2.2, hitstun: 0.20, energyGain: 6,
    color,
  };
  const skill1 = skill1Type === 'melee'
    ? {
        key: 'skill1', name: skill1Name, short: '技1', type: 'melee',
        damage: skillDamage, range: 2.6, arc: 1.35,
        startup: 0.13, active: 0.12, recovery: 0.23,
        cooldown: 4.4, cost: 20,
        knockback: 4.2, hitstun: 0.33,
        slowMs: 1200, slowFactor: 0.6,
        color,
      }
    : {
        key: 'skill1', name: skill1Name, short: '技1', type: 'dash',
        damage: skillDamage, range: 2.7, arc: 1.15,
        startup: 0.10, active: 0.18, recovery: 0.22,
        cooldown: 4.2, cost: 20,
        dashSpeed: 9.0, knockback: 5.2, hitstun: 0.34,
        color,
      };
  return {
    attack,
    skill1,
    skill2: {
      key: 'skill2', name: skill2Name, short: '技2', type: 'projectile', style: skill2Style,
      damage: projectileDamage, speed: 12.5, radius: 0.3, life: 1.7,
      startup: 0.20, active: 0.05, recovery: 0.28,
      cooldown: 5.4, cost: skill2Cost,
      knockback: 3.1, hitstun: 0.27,
      color: projectileColor, trail: projectileTrail,
    },
    ultimate: {
      key: 'ultimate', name: ultName, short: '奥', type: 'ultimate',
      damage: ultDamage, range: 3.7, arc: 1.55,
      startup: 0.42, active: 0.30, recovery: 0.55,
      cooldown: 18, cost: 100,
      knockback: 9.0, hitstun: 0.65,
      color: ultColor, trail: color,
    },
  };
}

